// Kịch bản mẫu quay dashboard (REC_NOCURSOR=1): lọc → rê chuột → "…" → Tạo Insight → Xuất HTML deck.
// Một mạch (quay với REC_NOCURSOR=1): lọc Kênh = Online → bỏ lọc → rê chuột dọc đường dự báo → "…" → Tạo Insight → chờ tóm tắt → đóng
// → "…" → Xuất PowerPoint (AI) → chọn HTML deck → lướt tới Xuất → Hủy.
const URL = process.env.DASH_URL || 'https://app.example.com/vi/analysis/dashboards/<dashboard-id>'
const M = 480
export default async ({ page, move, click, clickAt, wait, mark }) => {
    await page.goto(URL, { waitUntil: 'domcontentloaded' })
    await page.getByText('Bộ lọc chung').first().waitFor({ timeout: 90000 })
    await wait(25000)
    // làm nóng danh sách giá trị Kênh (lần đầu tải chậm) rồi đóng lại, để lúc quay mở ra là có ngay
    await page.mouse.click(228, 393)
    await page.getByText('Online', { exact: true }).last().waitFor({ timeout: 90000 })
    await page.keyboard.press('Escape')
    await wait(2500)
    await move(900, 520, 300)
    mark('filterStart')
    await clickAt(228, 393, 'channel', M)
    await wait(900)
    await click(page.getByText('Online', { exact: true }).last(), { label: 'online', ms: M })
    await wait(600)
    await page.keyboard.press('Escape')
    mark('filterApplied')
    await wait(9000)
    mark('filterUndo')
    await clickAt(228, 393, 'channel2', M)
    await wait(900)
    await click(page.getByText('Online', { exact: true }).last(), { label: 'online-off', ms: M })
    await wait(600)
    await page.keyboard.press('Escape')
    await wait(9000)
    mark('hoverStart')
    for (const [x, y] of [[1287, 690], [1455, 650], [1497, 675], [1624, 671], [1748, 668]]) {
        await move(x, y, 650)
        await wait(1200)
    }
    mark('hoverEnd')
    await move(1300, 300, M)
    mark('menuStart')
    await clickAt(1891, 64, 'menu', M)
    await wait(800)
    await click(page.getByRole('menuitem', { name: 'Tạo Insight' }), { label: 'insight', ms: M })
    mark('insightClicked')
    await page.getByRole('button', { name: /Ghim làm Widget/ }).first().waitFor({ timeout: 180000 })
    mark('insightResult')
    await wait(3500)
    await move(960, 620, M)
    await wait(2500)
    await page.keyboard.press('Escape')
    await wait(1500)
    mark('deckStart')
    await clickAt(1891, 64, 'menu2', M)
    await wait(800)
    await click(page.getByRole('menuitem', { name: 'Xuất PowerPoint (AI)' }), { label: 'pptItem', ms: M })
    await wait(1600)
    mark('dialog')
    await click(page.getByRole('dialog').getByRole('combobox').first(), { label: 'format', ms: M })
    await wait(800)
    await click(page.getByRole('option', { name: /HTML deck/ }), { label: 'htmlDeck', ms: M })
    await wait(700)
    const exportBtn = page.getByRole('button', { name: 'Xuất', exact: true })
    const box = await exportBtn.boundingBox().catch(() => null)
    if (box) await move(box.x + box.width / 2, box.y + box.height / 2, M)
    mark('hoverExport')
    await wait(1500)
    await click(page.getByRole('button', { name: 'Hủy' }), { label: 'cancel', ms: 400 })
    await wait(800)
}
